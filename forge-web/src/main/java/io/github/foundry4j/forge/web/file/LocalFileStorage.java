package io.github.foundry4j.forge.web.file;

import io.github.foundry4j.forge.core.error.CommonErrorCode;
import io.github.foundry4j.forge.core.exception.BusinessException;
import io.github.foundry4j.forge.web.ForgeWebProperties;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardOpenOption;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.UUID;

/// Local disk implementation of [FileStorage].
///
/// Files are laid out in date based directories so that a single directory never
/// grows unbounded:
///
/// ```text
/// {base-dir}/2026/11/09/8f3a....pdf
/// ```
///
/// Keys are generated by the storage, never supplied by the client, which removes
/// path traversal as an attack surface. Every resolved path is still checked to stay
/// inside the root directory.
public class LocalFileStorage implements FileStorage {

    private static final DateTimeFormatter DATE_DIRS = DateTimeFormatter.ofPattern("yyyy/MM/dd");
    private static final int BUFFER_SIZE = 8192;

    private final Path root;
    private final long maxSize;
    private final List<String> allowedContentTypes;

    /// Creates the storage and prepares the root directory.
    public LocalFileStorage(ForgeWebProperties.File properties) {
        this.root = Paths.get(properties.baseDir()).toAbsolutePath().normalize();
        this.maxSize = properties.maxSize().toBytes();
        this.allowedContentTypes = properties.allowedContentTypes().stream()
                .map(type -> type.trim().toLowerCase(Locale.ROOT))
                .toList();
        try {
            Files.createDirectories(root);
        } catch (IOException ex) {
            throw new IllegalStateException("Cannot create file storage directory " + root, ex);
        }
    }

    @Override
    public StoredFile store(InputStream in, String originalFilename, String contentType) {
        String normalizedType = normalizeContentType(contentType);
        assertContentTypeAllowed(normalizedType);

        String key = buildKey(originalFilename);
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
        } catch (IOException ex) {
            throw new BusinessException(CommonErrorCode.INTERNAL_ERROR, "Cannot create storage directory", ex);
        }

        long total = 0;
        boolean success = false;
        try (OutputStream out = Files.newOutputStream(target, StandardOpenOption.CREATE_NEW)) {
            byte[] buffer = new byte[BUFFER_SIZE];
            int read;
            while ((read = in.read(buffer)) != -1) {
                total += read;
                if (total > maxSize) {
                    throw new BusinessException(CommonErrorCode.PAYLOAD_TOO_LARGE,
                            "File exceeds the maximum size of %d bytes".formatted(maxSize));
                }
                out.write(buffer, 0, read);
            }
            success = true;
        } catch (IOException ex) {
            throw new BusinessException(CommonErrorCode.INTERNAL_ERROR, "Failed to write file", ex);
        } finally {
            if (!success) {
                deleteQuietly(target);
            }
        }
        return new StoredFile(key, sanitizeFilename(originalFilename), normalizedType, total);
    }

    @Override
    public InputStream open(String key) throws IOException {
        Path path = resolve(key);
        return Files.isRegularFile(path) ? Files.newInputStream(path) : null;
    }

    @Override
    public boolean exists(String key) {
        return Files.isRegularFile(resolve(key));
    }

    @Override
    public void delete(String key) {
        deleteQuietly(resolve(key));
    }

    /// Resolves a key and rejects anything that would escape the root directory.
    private Path resolve(String key) {
        if (key == null || key.isBlank()) {
            throw new BusinessException(CommonErrorCode.BAD_REQUEST, "File key must not be blank");
        }
        Path path = root.resolve(key).toAbsolutePath().normalize();
        if (!path.startsWith(root)) {
            throw new BusinessException(CommonErrorCode.BAD_REQUEST, "Illegal file key");
        }
        return path;
    }

    private String buildKey(String originalFilename) {
        return LocalDate.now().format(DATE_DIRS) + "/"
                + UUID.randomUUID().toString().replace("-", "") + extensionOf(originalFilename);
    }

    private String extensionOf(String filename) {
        String safe = sanitizeFilename(filename);
        int dot = safe.lastIndexOf('.');
        if (dot <= 0 || dot == safe.length() - 1) {
            return "";
        }
        String extension = safe.substring(dot + 1).toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]", "");
        return extension.isEmpty() || extension.length() > 10 ? "" : "." + extension;
    }

    private String sanitizeFilename(String filename) {
        if (filename == null || filename.isBlank()) {
            return "file";
        }
        String name = filename.replace('\\', '/');
        int slash = name.lastIndexOf('/');
        if (slash >= 0) {
            name = name.substring(slash + 1);
        }
        String cleaned = name.replaceAll("[\\p{Cntrl}]", "").trim();
        return cleaned.isEmpty() ? "file" : cleaned;
    }

    private String normalizeContentType(String contentType) {
        if (contentType == null || contentType.isBlank()) {
            return "application/octet-stream";
        }
        return contentType.split(";", 2)[0].trim().toLowerCase(Locale.ROOT);
    }

    private void assertContentTypeAllowed(String contentType) {
        if (!allowedContentTypes.isEmpty() && !allowedContentTypes.contains(contentType)) {
            throw new BusinessException(CommonErrorCode.UNSUPPORTED_MEDIA_TYPE,
                    "Unsupported file type [%s]".formatted(contentType));
        }
    }

    private void deleteQuietly(Path path) {
        try {
            Files.deleteIfExists(path);
        } catch (IOException _) {
            // Cleanup failure must not mask the original error
        }
    }
}
