create table forge_audit_log
(
    id          bigint generated by default as identity primary key,
    entity_type varchar(128)                not null,
    entity_id   varchar(64),
    action      varchar(16)                 not null,
    actor       varchar(64),
    changes     varchar(4000),
    occurred_at timestamp(6) with time zone not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    created_by  varchar(64),
    updated_by  varchar(64),
    version     bigint                      not null,
    deleted     boolean                     not null default false
);

create index idx_audit_entity on forge_audit_log (entity_type, entity_id);
create index idx_audit_actor on forge_audit_log (actor);

create table forge_operation_log
(
    id           bigint generated by default as identity primary key,
    trace_id     varchar(64),
    actor        varchar(64),
    action       varchar(128)                not null,
    target       varchar(256),
    arguments    varchar(4000),
    result       varchar(4000),
    error        varchar(2000),
    cost_millis  bigint                      not null,
    client_ip    varchar(64),
    user_agent   varchar(512),
    occurred_at  timestamp(6) with time zone not null,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    created_by   varchar(64),
    updated_by   varchar(64),
    version      bigint                      not null,
    deleted      boolean                     not null default false
);

create index idx_operation_actor on forge_operation_log (actor);
create index idx_operation_occurred on forge_operation_log (occurred_at);
