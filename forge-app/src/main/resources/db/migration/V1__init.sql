create table forge_order
(
    id            bigint generated by default as identity primary key,
    tenant_id     varchar(64)                 not null,
    order_no      varchar(64)                 not null,
    customer_name varchar(128)                not null,
    phone         varchar(32),
    amount        numeric(19, 2)              not null,
    status        varchar(16)                 not null,
    remark        varchar(512),
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    created_by    varchar(64),
    updated_by    varchar(64),
    version       bigint                      not null,
    deleted       boolean                     not null default false
);

create index idx_forge_order_tenant_status on forge_order (tenant_id, status);
create index idx_forge_order_no on forge_order (order_no);

create table forge_dict_type
(
    id         bigint generated by default as identity primary key,
    code       varchar(64)                 not null,
    name       varchar(128)                not null,
    remark     varchar(512),
    enabled    boolean                     not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    created_by varchar(64),
    updated_by varchar(64),
    version    bigint                      not null,
    deleted    boolean                     not null default false,
    constraint uk_forge_dict_type_code unique (code)
);

create table forge_dict_item
(
    id             bigint generated by default as identity primary key,
    dict_type_code varchar(64)                 not null,
    label          varchar(128)                not null,
    item_value     varchar(128)                not null,
    sort_no        integer                     not null,
    enabled        boolean                     not null,
    extra          varchar(1024),
    created_at     timestamp(6) with time zone not null,
    updated_at     timestamp(6) with time zone not null,
    created_by     varchar(64),
    updated_by     varchar(64),
    version        bigint                      not null,
    deleted        boolean                     not null default false
);

create index idx_forge_dict_item_type on forge_dict_item (dict_type_code);

create table forge_outbox_event
(
    id              bigint generated by default as identity primary key,
    message_id      varchar(64)                 not null,
    event_type      varchar(160)                not null,
    destination     varchar(200)                not null,
    payload         varchar(65535)              not null,
    message_headers varchar(65535)              not null,
    tenant_id       varchar(64),
    status          varchar(16)                 not null,
    attempts        integer                     not null,
    last_error      varchar(1000),
    next_attempt_at timestamp(6) with time zone not null,
    occurred_at     timestamp(6) with time zone not null,
    sent_at         timestamp(6) with time zone,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    constraint uk_forge_outbox_message_id unique (message_id)
);

create index idx_forge_outbox_status on forge_outbox_event (status, next_attempt_at);

