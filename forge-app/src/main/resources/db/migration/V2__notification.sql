create table forge_notification
(
    id              bigint generated by default as identity primary key,
    tenant_id       varchar(64)                 not null,
    channel         varchar(16)                 not null,
    recipient       varchar(320)                not null,
    subject         varchar(200)                not null,
    content         varchar(65535)              not null,
    status          varchar(16)                 not null,
    attempts        integer                     not null,
    last_error      varchar(1000),
    next_attempt_at timestamp(6) with time zone not null,
    sent_at         timestamp(6) with time zone,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    created_by      varchar(64),
    updated_by      varchar(64),
    version         bigint                      not null,
    deleted         boolean                     not null default false
);

create index idx_forge_notification_status on forge_notification (status, next_attempt_at);
create index idx_forge_notification_tenant on forge_notification (tenant_id, created_at);
